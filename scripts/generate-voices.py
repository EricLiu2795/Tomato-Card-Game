async def generate(reaction: dict[str, str], output: Path) -> None:
    try:
        import edge_tts
    except ImportError as error:  # pragma: no cover - exercised by CLI users
        raise SystemExit(
            "edge-tts is required; install it with "
            "'py -3 -m pip install edge-tts==7.3.1'"
        ) from error

    communicate = edge_tts.Communicate(
        reaction["text"],
        reaction["voice"],
        rate=reaction["rate"],
        pitch=reaction["pitch"],
        volume="+0%",
    )
    await communicate.save(str(output))


async def main(force: bool, only: list[str] | None) -> None:
    OUTPUT_DIR.mkdir(parents=True, exist_ok=True)
    for reaction in REACTIONS:
        if only and reaction["id"] not in only:
            continue
        output = OUTPUT_DIR / f"{reaction['id']}.mp3"
        if output.exists() and not force:
            print(f"skip {output.name} (already exists; use --force to regenerate)")
            continue
        print(
            f"generate {output.name}: {reaction['voice']} "
            f"rate={reaction['rate']} pitch={reaction['pitch']}"
        )
        await generate(reaction, output)


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--force",
        action="store_true",
        help="regenerate clips that already exist",
    )
    parser.add_argument(
        "--only",
        action="append",
        choices=[reaction["id"] for reaction in REACTIONS],
        metavar="ID",
        help="regenerate only this reaction (can be repeated)",
    )
    args = parser.parse_args()
    asyncio.run(main(args.force, args.only))
