"""Generate the soundboard's Mandarin reaction clips with Edge neural voices.

The files are synthetic neural speech generated by Microsoft's public Edge TTS
service through the ``edge-tts`` package. They are not actor recordings and do
not clone a real person. Install the small, open-source client once with:

    py -3 -m pip install edge-tts==7.3.1

Run this script from the repository root (or from any working directory):

    py -3 scripts/generate-voices.py

The service is online, so generation needs network access. The resulting MP3s
are committed as ordinary static assets so the game does not synthesize speech
at play time.
"""

